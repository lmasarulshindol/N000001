def normalize(text: str) -> str:
    t = text.replace("♡", "")
    t = t.replace("森さん", "モリさん").replace("もりさん", "モリさん")
    t = t.replace("特等席", "とくとうせき")
    t = t.replace("二回", "にかい")
    t = re.sub(r"\s+", "", t)
    return t


def main() -> None:
    items: list[dict] = []
    n = 0
    for text, line_cap in LINES:
        spoken = normalize(text)
        chunks = split_into_chunks(spoken) if len(spoken) > 55 else [spoken]
        for chunk in chunks:
            chunk = chunk.strip("、")
            if not chunk:
                continue
            n += 1
            items.append(
                {
                    "text": chunk,
                    "caption": line_cap,
                    "seed": SEED,
                    "output_wav": str(OUT_DIR / f"h{n:03d}.wav"),
                }
            )
    manifest = {
        "hf_checkpoint": "Aratako/Irodori-TTS-v4.1-Small",
        "model_device": "cuda",
        "codec_device": "cuda",
        "codec_repo": "Aratako/Semantic-DACVAE-Japanese-32dim",
        "model_precision": "fp32",
        "codec_precision": "fp32",
        "codec_deterministic_encode": True,
        "codec_deterministic_decode": True,
        "enable_watermark": False,
        "compile_model": False,
        "compile_dynamic": False,
        "num_steps": 40,
        "cfg_scale_text": 3.0,
        "cfg_scale_caption": 4.0,
        "no_ref": True,
        "caption": ROOT,
        "max_seconds": 14,
        "trim_tail": True,
        "tail_std_threshold": 0.05,
        "items": items,
    }
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    long = [it["text"] for it in items if len(it["text"]) > 55]
    print(f"items {len(items)} long {len(long)}")
    for it in items:
        if len(it["text"]) > 55:
            print("LONG", len(it["text"]), it["text"])


if __name__ == "__main__":
    main()
